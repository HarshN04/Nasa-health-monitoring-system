"""
Turns NASA's "Flight Crew Physiological Data for Crew State Monitoring"
LOFT CSV (a full 68-minute simulated flight) into a small data file the Tests page can load offline.

Source: https://data.nasa.gov/dataset/flight-crew-physiological-data-for-crew-state-monitoring
Columns used: TimeSecs, R (respiration belt), GSR (skin conductance), Event.
Event codes: 0 = no event (baseline), 1 = startle/surprise (SS),
             2 = channelized attention (CA), 5 = diverted attention (DA).

ECG is NOT used: in this sample it is too noisy for a reliable heart rate
(and it is empty in the DA file). EEG is not used either.

Usage (from the repo root):
    pip install pandas numpy scipy
    python tools/process_crew_data.py data/raw/5_LOFT.csv
Writes: data/crew-state-data.js
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.signal import butter, filtfilt, find_peaks

FS = 256              # samples per second (from the dataset page)
WINDOW_S = 30         # one value every 30 seconds
SCR_PROMINENCE = 15   # minimum GSR rise counted as a "stress response" (SCR)
BASELINE_END_S = 660  # LOFT: first 11 min, before the first event, is "your normal"
EVENT_NAMES = {0: "No event", 1: "Startle / surprise", 2: "Channelized attention", 5: "Diverted attention"}


def lowpass(x, cutoff_hz):
    b, a = butter(3, cutoff_hz / (FS / 2), "low")
    return filtfilt(b, a, x)


def window_features(df):
    """Breathing rate and stress responses for each 30-second window."""
    breath_sig = lowpass(df["R"].to_numpy() - df["R"].mean(), 0.7)
    gsr_sig = lowpass(df["GSR"].to_numpy(), 1.0)
    t = df["TimeSecs"].to_numpy()
    ev = df["Event"].to_numpy().astype(int)
    rows = []
    n_windows = int((t[-1] - t[0]) // WINDOW_S)
    for i in range(n_windows):
        start = t[0] + i * WINDOW_S
        idx = np.flatnonzero((t >= start) & (t < start + WINDOW_S))
        if len(idx) < FS * WINDOW_S * 0.9:
            continue
        b = breath_sig[idx]
        breaths, _ = find_peaks(b, distance=2 * FS, prominence=max(np.std(b) * 0.3, 0.3))
        scrs, _ = find_peaks(gsr_sig[idx], prominence=SCR_PROMINENCE)
        rows.append({
            "t": int(round(start)),
            "breath": round(len(breaths) * 60 / WINDOW_S, 1),
            "stress": round(len(scrs) * 60 / WINDOW_S, 1),
            "event": int(ev[idx].max()),
        })
    return pd.DataFrame(rows)


def mean_sd(series):
    return {"mean": round(float(series.mean()), 1), "sd": round(float(series.std()), 1)}


def main(loft_path):
    loft = pd.read_csv(loft_path, usecols=["TimeSecs", "R", "GSR", "Event"])
    f = window_features(loft)
    base = f[(f.t < BASELINE_END_S) & (f.event == 0)]
    normal = {"breath": mean_sd(base.breath), "stress": mean_sd(base.stress)}

    by_state = []
    for code, group in f.groupby("event"):
        by_state.append({
            "code": int(code),
            "name": EVENT_NAMES.get(int(code), str(code)),
            "windows": len(group),
            "stress": round(float(group.stress.mean()), 1),
            "breath": round(float(group.breath.mean()), 1),
        })

    data = {
        "source": {
            "title": "Flight Crew Physiological Data for Crew State Monitoring",
            "publisher": "NASA (Langley Research Center)",
            "url": "https://data.nasa.gov/dataset/flight-crew-physiological-data-for-crew-state-monitoring",
            "subject": "Crew 5, one crew member",
            "note": "Pilots in a flight simulator, used here as a stand-in for astronaut data.",
        },
        "method": {
            "windowSeconds": WINDOW_S,
            "baselineMinutes": BASELINE_END_S // 60,
            "watchRule": "Outside your normal = more than 2 standard deviations from your baseline mean.",
            "signals": {
                "breath": "Breaths per minute, from the respiration belt (R).",
                "stress": "Stress responses per minute: quick rises in skin conductance (GSR).",
            },
        },
        "session": {
            "name": "Full simulated flight (LOFT)",
            "minutes": round(float(loft.TimeSecs.iloc[-1]) / 60),
            "normal": normal,
            "byState": by_state,
            # compact: [secondsFromStart, breathsPerMin, stressResponsesPerMin, eventCode]
            "windows": "__WINDOWS__",
        },
    }

    out = Path(__file__).resolve().parent.parent / "data" / "crew-state-data.js"
    header = (
        "// Generated by tools/process_crew_data.py. Do not edit by hand.\n"
        "// A .js file (not .json) so the page also works when opened straight from a folder (offline).\n"
        "// Load it after js/data.js. Read it as CHM.CREW_STATE.\n"
    )
    windows = ",\n      ".join(
        json.dumps([int(r.t), float(r.breath), float(r.stress), int(r.event)]) for r in f.itertuples()
    )
    text = json.dumps(data, indent=2).replace('"__WINDOWS__"', "[\n      " + windows + "\n    ]")
    out.write_text(header + "window.CHM = window.CHM || {};\nwindow.CHM.CREW_STATE = " + text + ";\n")
    print(f"Wrote {out} ({len(f)} windows). Normal: {normal}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(*sys.argv[1:])
